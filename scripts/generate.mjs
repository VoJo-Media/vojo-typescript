// Renders src/generated from the shared contract files. `--check` renders to a
// temporary directory and fails if the committed copy differs.
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// Monorepo: ../shared. Public repo: ./shared.
const shared = existsSync(join(root, "shared")) ? join(root, "shared") : resolve(root, "../shared");
const { api_version: apiVersion, operations, events } = JSON.parse(readFileSync(join(shared, "api/operations.json"), "utf8"));
const { version: sdkVersion } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const spec = JSON.parse(readFileSync(join(shared, "api/vojo-api.public.json"), "utf8"));

const NOTICE = "// Generated by scripts/generate.mjs from the Vojo API contract. Do not edit.\n";
const camel = (name) => name.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (chain) => chain.map((part) => part[0].toUpperCase() + part.slice(1)).join("");
const comment = (lines, indent) =>
    [`${indent}/**`, ...lines.map((line) => `${indent} * ${line.replaceAll("*/", "* /")}`.trimEnd()), `${indent} */`].join("\n");

const docLines = (op) => {
    const lines = [op.summary ?? `${op.http_method} ${op.path}`, "", `\`${op.http_method} ${op.path}\``];
    if (op.scopes.length) lines.push(`Needs scope: ${op.scopes.join(", ")}.`);
    if (!op.auth.includes("secretKey")) lines.push("Needs a user (OAuth) access token: secret keys are rejected.");
    if (!op.available_in_early_access) lines.push("Not available yet during early access: the API answers 404.");
    return lines;
};

const renderMethod = (op) => {
    const t = `operations["${op.operation_id}"]`;
    const statuses = op.response.statuses.join(" | ");
    const json = `${t}["responses"][${statuses}]["content"]["application/json"]`;
    const args = op.path_params.map((p) => `${camel(p)}: string`);
    const opFields = [`method: "${op.http_method}"`];
    const path = op.path.replace(/\{(\w+)\}/g, (_, p) => `\${encodePathParam("${camel(p)}", ${camel(p)})}`);
    opFields.push(`path: \`${path}\``);

    if (op.request_body) {
        const bodyType = op.request_body.schema ? `M.${op.request_body.schema}` : `NonNullable<${t}["requestBody"]>["content"]["application/json"]`;
        args.push(`body${op.request_body.required ? "" : "?"}: ${bodyType}`);
        opFields.push("body");
    } else if (op.query_params.length) {
        const required = op.query_params.some((p) => p.required);
        args.push(`query${required ? "" : "?"}: NonNullable<${t}["parameters"]["query"]>`);
        opFields.push("query");
    }
    args.push("options?: RequestOptions");
    opFields.push(`idempotent: ${op.idempotency_key}`, `retrySafe: ${op.retry_safe}`, `availableInEarlyAccess: ${op.available_in_early_access}`, "options");
    const literal = `{ ${opFields.join(", ")} }`;

    const { returns, data_schema: dataSchema, item_schema: itemSchema, is_array: isArray } = op.response;
    const item = itemSchema ? `M.${itemSchema}` : `${json}["data"][number]`;
    const data = dataSchema ? `M.${dataSchema}` : isArray ? `${item}[]` : `${json}["data"]`;

    const signature = `${op.method}(${args.join(", ")})`;
    const render = (result, call) => `${signature}: ${result} {\n        return ${call};\n    }`;
    const body = {
        void: () => render("Promise<void>", `sendForVoid(this.transport, ${literal})`),
        page: () => render(`PagedList<${item}>`, `pagedList<${item}>(this.transport, ${literal})`),
        envelope: () => render(`Promise<WithResponse<${json}>>`, `sendForEnvelope<${json}>(this.transport, ${literal})`),
        data: () => render(`Promise<WithResponse<${data}>>`, `sendForData<${data}>(this.transport, ${literal})`),
    }[returns]();
    return `${comment(docLines(op), "    ")}\n    ${body}`;
};

const buildTree = () => {
    const rootNode = { chain: [], children: new Map(), ops: [] };
    for (const op of operations) {
        let node = rootNode;
        for (const part of op.resource) {
            if (!node.children.has(part)) node.children.set(part, { chain: [...node.chain, part], children: new Map(), ops: [] });
            node = node.children.get(part);
        }
        node.ops.push(op);
    }
    return rootNode;
};

const renderClass = (name, node, exported) => {
    const children = [...node.children.entries()];
    const fields = children.map(([part, child]) => `    readonly ${part}: ${pascal(child.chain)};`);
    const assigns = children.map(([part, child]) => `        this.${part} = new ${pascal(child.chain)}(transport);`);
    const parts = [
        ...fields,
        ...(fields.length ? [""] : []),
        `    constructor(${node.ops.length ? "protected readonly " : ""}transport: Transport) {`,
        ...assigns,
        "    }",
        ...node.ops.flatMap((op) => ["", renderMethod(op)]),
    ];
    return `${exported ? "export " : ""}class ${name} {\n${parts.join("\n")}\n}\n`;
};

const renderResources = () => {
    const classes = [];
    const visit = (node) => {
        for (const child of node.children.values()) {
            visit(child);
            classes.push(renderClass(pascal(child.chain), child, true));
        }
    };
    const tree = buildTree();
    visit(tree);
    classes.push(renderClass("VojoResources", tree, true));
    return `${NOTICE}/* eslint-disable */
import { encodePathParam, sendForData, sendForEnvelope, sendForVoid, type RequestOptions, type Transport, type WithResponse } from "../core";
import { pagedList, type PagedList } from "../pagination";
import type * as M from "./models";
import type { operations } from "./schema";

${classes.join("\n")}`;
};

// Declared by the runtime, with room for unknown members.
const OWN_TYPES = new Set(["Problem"]);

const renderModels = () => {
    const names = Object.keys(spec.components.schemas).filter((name) => !name.endsWith("Envelope") && !OWN_TYPES.has(name));
    return `${NOTICE}import type { components } from "./schema";\n\n${names
        .map((name) => `export type ${name} = components["schemas"]["${name}"];`)
        .join("\n")}\n`;
};

const renderEvents = () => {
    const payloads = [...new Set(events.map((event) => event.schema))];
    const members = events.map(
        (event) => `    | { type: "${event.type}"; id: string; attempt_id: string | null; payload: ${event.schema} }`
    );
    return `${NOTICE}import type { components } from "./webhooks-schema";

${payloads.map((name) => `export type ${name} = components["schemas"]["${name}"];`).join("\n")}

/** A verified webhook delivery. New event types can arrive at runtime: keep a default branch when you switch on \`type\`. */
export type WebhookEvent =
${members.join("\n")};

export type WebhookEventType = WebhookEvent["type"];
`;
};

const renderVersion = () =>
    `${NOTICE}export const API_VERSION = "${apiVersion}";\nexport const SDK_VERSION = "${sdkVersion}";\n`;

const renderApiDoc = () => {
    const rows = operations.map((op) => {
        const args = op.path_params.map(camel);
        if (op.request_body) args.push(op.request_body.required ? "body" : "body?");
        else if (op.query_params.length) args.push("query?");
        const note = op.auth.includes("secretKey") ? "" : "OAuth only";
        return `| \`vojo.${op.resource.join(".")}.${op.method}(${args.join(", ")})\` | \`${op.http_method} ${op.path}\` | ${op.available_in_early_access ? "Yes" : "Not yet"} | ${note} |`;
    });
    return `<!-- Generated by scripts/generate.mjs. Do not edit. -->

# API reference

API version \`${apiVersion}\`. "Early access" says whether the API serves the operation today. The others answer 404 until they ship, and need no new SDK when they do.

| Method | Request | Early access | Note |
| --- | --- | --- | --- |
${rows.join("\n")}
`;
};

const generate = (dir) => {
    mkdirSync(dir, { recursive: true });
    const bin = join(root, "node_modules/.bin/openapi-typescript");
    for (const [input, output] of [
        ["vojo-api.public.json", "schema.d.ts"],
        ["vojo-webhooks.public.json", "webhooks-schema.d.ts"],
    ]) {
        // A field with a default is optional in a request, so defaults must not make it required.
        execFileSync(bin, [join(shared, "api", input), "-o", join(dir, output), "--default-non-nullable=false"], { stdio: "pipe" });
    }
    writeFileSync(join(dir, "resources.ts"), renderResources());
    writeFileSync(join(dir, "models.ts"), renderModels());
    writeFileSync(join(dir, "events.ts"), renderEvents());
    writeFileSync(join(dir, "version.ts"), renderVersion());
    writeFileSync(join(dir, "API.md"), renderApiDoc());
};

const target = join(root, "src/generated");
if (process.argv.includes("--check")) {
    const dir = mkdtempSync(join(tmpdir(), "vojo-generated-"));
    try {
        generate(dir);
        const names = new Set([...readdirSync(dir), ...readdirSync(target)]);
        const stale = [...names].filter((name) => {
            const a = join(dir, name);
            const b = join(target, name);
            return !existsSync(a) || !existsSync(b) || readFileSync(a, "utf8") !== readFileSync(b, "utf8");
        });
        if (stale.length) {
            console.error(`Generated code is stale: ${stale.join(", ")}. Run npm run generate.`);
            process.exit(1);
        }
        console.log("Generated code is up to date.");
    } finally {
        rmSync(dir, { recursive: true, force: true });
    }
} else {
    generate(target);
    console.log(`Generated ${operations.length} operations and ${events.length} events.`);
}
